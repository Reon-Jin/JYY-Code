export function runInstructions(input: {
  runID: string
  artifactDir: string
  simpleModel: string
  complexModel: string
  visualModel: string
  reviewerModel: string
  maxSubagents: number
  maxConcurrency: number
  maxReviewRounds: number
}) {
  return [
    "<agent-cluster-run>",
    `run_id: ${input.runID}`,
    `artifact_dir: ${input.artifactDir}`,
    `simple_model: ${input.simpleModel}`,
    `complex_model: ${input.complexModel}`,
    `visual_model: ${input.visualModel}`,
    `reviewer_model: ${input.reviewerModel}`,
    `max_subagents: ${input.maxSubagents}`,
    `max_concurrency: ${input.maxConcurrency}`,
    `max_review_rounds: ${input.maxReviewRounds}`,
    "",
    "Limits: the full plan must not exceed max_subagents. A single dependency step must not exceed max_concurrency.",
    "",
    "=== PLAN-FIRST ===",
    "FIRST: present the complete plan as a JSON block + natural language summary. Only then dispatch step 1 tasks.",
    "",
    "Planning: plan tasks as dependency steps. Step 1 tasks have dependencies=[] and must be dispatched together immediately after the plan is presented. For step i, every task may depend only on tasks from steps 1..i-1; tasks in the same step must not depend on each other.",
    "",
    "Parallelism: max_concurrency is the upper bound for one dependency step. Task calls run in the background in cluster mode. Dispatch all currently ready tasks before waiting for results. If several planned steps have no dependency path between them, treat them as ready together and dispatch them together, subject to max_concurrency per step.",
    "Do not stop after presenting the plan. The same assistant response that presents the plan must also include task tool calls for every ready step-1 task.",
    "",
    "Required task plan JSON shape:",
    '{"goal":"...","tasks":[{"id":"...","step":1,"title":"...","role":"researcher|analyst|writer|chart|pdf|coder|tester|reviewer|general","complexity":"simple|complex","model":"...","dependencies":[],"prompt":"...","acceptanceCriteria":["..."],"expectedArtifacts":["..."]}]}',
    "",
    "=== MANDATORY REVIEW ===",
    "After each step's subagents complete, you MUST review every result using the structured review format:",
    "```review",
    "task_id: <id>  ← MUST be the \"ses_...\" session ID returned by the task tool, NOT your plan's id",
    "decision: accepted|revision_requested|failed",
    'issues: <specific issues or "none">',
    'revision_prompt: <revision instructions or "none">',
    "```",
    `Respect max_review_rounds=${input.maxReviewRounds}. For revisions, use the session ID (ses_...) as task_id — never use your plan's internal id.`,
    "",
    "Model routing:",
    `- default to ${input.complexModel} for all ordinary tasks, including simple and complex work`,
    `- use ${input.visualModel} for tasks that need visual capability, image search, image evaluation, PDF/PPT/DOCX layout, presentation or document production, polished charts, diagrams, tables, visual assets, or export-ready visual artifacts`,
    `- use ${input.visualModel} for chart and pdf roles unless the user explicitly requests a different model`,
    `- use ${input.reviewerModel} for reviewer tasks`,
    "- if the user explicitly requested a model for a task, use that model",
    "- when calling task, pass the chosen model in the model field",
    "",
    "Artifact routing:",
    `- write plan artifacts under ${input.artifactDir}`,
    "- ask each subagent to write its artifacts to the expected paths and return a concise summary plus artifact list",
    "</agent-cluster-run>",
  ].join("\n")
}
